#!/usr/bin/env python3
"""Turn vectors.json into a C header of v6 tx + PSBT fixtures for test_zec_v6.c."""
import json
import struct
import sys

BITGO_BRANCH_KEY = bytes.fromhex("fc05424954474f00")


def cs(n):
    if n < 0xFD:
        return bytes([n])
    if n <= 0xFFFF:
        return b"\xfd" + struct.pack("<H", n)
    return b"\xfe" + struct.pack("<I", n)


def kv(key: bytes, val: bytes) -> bytes:
    return cs(len(key)) + key + cs(len(val)) + val


def psbt(c, bitgo_branch=None):
    tx = bytes.fromhex(c["tx"])
    out = b"psbt\xff" + kv(b"\x00", tx)
    if bitgo_branch is not None:
        out += kv(BITGO_BRANCH_KEY, struct.pack("<I", bitgo_branch))
    out += b"\x00"
    for i in c["inputs"]:
        spk = bytes.fromhex(i["script_pubkey"])
        out += kv(b"\x01", struct.pack("<q", i["amount"]) + cs(len(spk)) + spk) + b"\x00"
    out += b"\x00" * len(c["outputs"])
    return out


def c_bytes(b: bytes) -> str:
    return '"' + b.hex() + '"'


def main(path):
    cases = [c for c in json.load(open(path))["cases"] if c["version"] == 6]
    print("/* Generated by gen_c_fixtures.py from vectors.json - do not edit. */")
    print("struct zec_v6_case {")
    print("    const char *name, *tx_hex, *psbt_hex, *psbt_bitgo_ok_hex, *psbt_bitgo_bad_hex;")
    print("    uint32_t branch_id, lock_time, expiry_height;")
    print("    size_t num_inputs, num_outputs;")
    print("    uint64_t first_output_value;")
    print("};")
    print("static const struct zec_v6_case ZEC_V6_CASES[] = {")
    for c in cases:
        print("    { %s,\n      %s,\n      %s,\n      %s,\n      %s,\n      0x%08xu, %du, %du, %d, %d, %dull }," % (
            json.dumps(c["name"]), c_bytes(bytes.fromhex(c["tx"])), c_bytes(psbt(c)),
            c_bytes(psbt(c, c["branch_id"])), c_bytes(psbt(c, c["branch_id"] ^ 1)),
            c["branch_id"], c["lock_time"], c["expiry_height"],
            len(c["inputs"]), len(c["outputs"]), c["outputs"][0]["value"]))
    print("};")


if __name__ == "__main__":
    main(sys.argv[1])
